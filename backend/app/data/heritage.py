def find_heritage_site(name: str):
    if not name:
        return None
    name_lower = name.lower().strip()

    for site in HERITAGE_SITES:
        if site["name"].lower() == name_lower or site["name"].lower() in name_lower or name_lower in site["name"].lower():
            return site

    return None